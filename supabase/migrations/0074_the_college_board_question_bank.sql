-- ============================================================================
--  0074 — room for College Board's question bank
--
--  The brief asks for College Board's SAT Suite Question Bank as the source of
--  practice questions, and its export holds 3,770 of them: 1,845 Reading and
--  Writing and 1,925 Mathematics, every one already carrying its domain, its
--  skill, its difficulty, its answer and College Board's own rationale. Against
--  the 175 questions the bank holds today, that is the difference between a
--  targeted test finding fresh questions on a skill and running out.
--
--  This is the room for them, not the questions themselves: the one skill the
--  export names that the app did not, and the loader that writes a question
--  into a subject's practice pool. The questions follow in the migrations
--  after it, generated by tools/questionbank.
--
--  COMMAND OF EVIDENCE. The app splits it in two — Textual and Quantitative —
--  because the teachers' evaluation grid does (0010). The export does not: all
--  277 of its Command of Evidence questions carry the one name. Rather than
--  guess which half each belongs to, the export's own name is added beside the
--  two, so a question is filed under exactly what College Board filed it
--  under. The existing two are untouched, and the questions already tagged
--  with them stay as they are.
--
--  WHERE THEY GO. The subject's practice pool (0060) — the set a targeted test
--  draws from and a lesson never shows — which is what the bank is for.
--
--  RE-RUNNABLE. seed_pool_question upserts on source_ref, as every content
--  migration here does (0010, 0065): running the import twice writes the same
--  bank, and a question already in the pool keeps its place in it.
-- ============================================================================

